logger = logging.getLogger(__name__)
MODEL_ID = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._-]{0,99}$")
PROVIDER = "gemini"
SIZE = "1K"
MAX_PROMPT_CHARS = 1000
DEFAULT_ASPECT = "1:1"
ASPECT_RATIOS = ("1:1", "4:3", "3:4", "16:9", "9:16")


def catalog() -> dict[str, dict[str, dict]]:
    """Administrator-approved image models and prices, in micro-USD."""
    try:
        raw = json.loads(get_settings().image_models_json)
        if not isinstance(raw, dict):
            raise ValueError("catalog")
        parsed: dict[str, dict[str, dict]] = {}
        for provider, models in raw.items():
            if provider != PROVIDER or not isinstance(models, dict):
                raise ValueError("provider")
            parsed[provider] = {}
            for model, sizes in models.items():
                if not MODEL_ID.fullmatch(model) or not isinstance(sizes, dict) or set(sizes) != {SIZE}:
                    raise ValueError("model")
                entry = sizes[SIZE]
                if not isinstance(entry, dict):
                    raise ValueError("entry")
                image_microusd = entry.get("image_microusd")
                input_rate = entry.get("input_microusd_per_million", 0)
                if (type(image_microusd) is not int or not 0 < image_microusd <= 1000000
                        or type(input_rate) is not int or not 0 <= input_rate <= 100000000):
                    raise ValueError("price")
                parsed[provider][model] = {SIZE: {"image_microusd": image_microusd,
                                                 "input_microusd_per_million": input_rate}}
        return parsed
    except (ValueError, TypeError, AttributeError) as exc:
        raise HTTPException(503, "Catálogo de imágenes de IA no válido") from exc


def models() -> list[dict]:
    result = []
    for model, sizes in catalog().get(PROVIDER, {}).items():
        entry = sizes[SIZE]
        # Upper bound for any prompt the API accepts (4 UTF-8 bytes per character at most), so the creation form can
        # confirm a total before the illustration prompts exist; each image is still estimated and confirmed exactly.
        worst = entry["image_microusd"] + cost(MAX_PROMPT_CHARS * 4 + 1024, 0,
                                               Price(entry["input_microusd_per_million"], 0))
        result.append({"provider": PROVIDER, "model": model, "sizes": [SIZE],
                       "prices": {SIZE: entry["image_microusd"]}, "max_cost_microusd": worst,
                       "input_microusd_per_million": entry["input_microusd_per_million"]})
    return sorted(result, key=lambda item: (item["prices"][SIZE], item["model"]))


def default_model() -> str | None:
    available = models()
    return available[0]["model"] if available else None


def price_for(model: str) -> dict:
    entry = catalog().get(PROVIDER, {}).get(model, {}).get(SIZE)
    if entry is None:
        raise HTTPException(403, "Modelo de imagen no habilitado")
    return entry


def estimate(prompt: str, model: str, aspect_ratio: str = DEFAULT_ASPECT) -> dict:
    if aspect_ratio not in ASPECT_RATIOS:
        raise HTTPException(422, "Proporción de imagen no válida")
    price = price_for(model)
    # One UTF-8 byte per token plus framing is a conservative upper bound, as in the text estimates.
    max_input_tokens = len(prompt.encode("utf-8")) + 1024
    input_microusd = cost(max_input_tokens, 0, Price(price["input_microusd_per_million"], 0))
    maximum = price["image_microusd"] + input_microusd
    fingerprint = hashlib.sha256(json.dumps({
        "provider": PROVIDER, "model": model, "size": SIZE, "aspect_ratio": aspect_ratio,
        "prompt": prompt, "image_microusd": price["image_microusd"],
        "input_microusd_per_million": price["input_microusd_per_million"],
    }, ensure_ascii=False, sort_keys=True).encode()).hexdigest()
    return {"provider": PROVIDER, "model": model, "size": SIZE, "aspect_ratio": aspect_ratio,
            "max_input_tokens": max_input_tokens, "maximum_cost_microusd": maximum,
            "image_microusd": price["image_microusd"], "input_microusd": input_microusd,
            "fingerprint": fingerprint}


def own_key(db: Session, user_id: UUID) -> bool:
    if temporary_credential(db, user_id, PROVIDER):
        return True
    return personal_credential(db, user_id, PROVIDER) is not None


def included_status(db: Session, user_id: UUID) -> dict | None:
    from . import included
    return included.image_status(db, user_id)


def configured(db: Session, user_id: UUID) -> bool:
    """The account can generate: with its own Gemini key, or with IA EduCrea when invited."""
    return own_key(db, user_id) or included_status(db, user_id) is not None


def uses_included(db: Session, user_id: UUID, model: str) -> bool:
    """IA EduCrea first for invited accounts (as with text), while it has images left this week for that model;
    otherwise the teacher's own key."""
    status = included_status(db, user_id)
    return status is not None and status["model"] == model and (status["remaining"] > 0 or not own_key(db, user_id))


def api_key(db: Session, user_id: UUID) -> str:
    temporary = temporary_credential(db, user_id, PROVIDER)
    if temporary:
        return temporary["key"].get_secret_value()
    credential = personal_credential(db, user_id, PROVIDER)
    if credential is None:
        raise HTTPException(409, "Configura tu clave de Gemini antes de generar imágenes")
    return decrypt_key(credential.ciphertext)


def daily_count(db: Session, user_id: UUID) -> int:
    today = datetime.combine(datetime.now(timezone.utc).date(), time.min, tzinfo=timezone.utc)
    image_models = list(catalog().get(PROVIDER, {}))
    if not image_models:
        return 0
    return int(db.scalar(select(func.count(AiUsage.id)).where(
        AiUsage.user_id == user_id, AiUsage.provider == PROVIDER, AiUsage.model.in_(image_models),
        AiUsage.created_at >= today)) or 0)


def check_daily_limit(db: Session, user_id: UUID) -> None:
    if daily_count(db, user_id) >= get_settings().ai_daily_image_requests:
        raise HTTPException(429, "Has alcanzado el límite diario de imágenes generadas")


def normalize(data: bytes) -> tuple[bytes, str]:
    """Strip metadata, cap the dimensions and make sure the result fits the asset library."""
    try:
        image = Image.open(io.BytesIO(data))
        image.load()
    except (UnidentifiedImageError, Image.DecompressionBombError, OSError, ValueError) as exc:
        raise HTTPException(502, "El proveedor devolvió una imagen no válida") from exc
    image = ImageOps.exif_transpose(image)
    has_alpha = image.mode in ("RGBA", "LA") or (image.mode == "P" and "transparency" in image.info)
    image = image.convert("RGBA" if has_alpha else "RGB")
    if max(image.size) > 1536:
        image.thumbnail((1536, 1536), Image.Resampling.LANCZOS)
    buffer = io.BytesIO()
    image.save(buffer, format="PNG", optimize=True)
    result = buffer.getvalue()
    if len(result) <= asset_service.MAX_IMAGE_BYTES:
        return result, "image/png"
    rgb = image.convert("RGB")
    buffer = io.BytesIO()
    rgb.save(buffer, format="JPEG", quality=88, optimize=True)
    result = buffer.getvalue()
    while len(result) > asset_service.MAX_IMAGE_BYTES and max(rgb.size) > 768:
        rgb.thumbnail((max(768, rgb.width * 3 // 4), max(768, rgb.height * 3 // 4)), Image.Resampling.LANCZOS)
        buffer = io.BytesIO()
        rgb.save(buffer, format="JPEG", quality=85, optimize=True)
        result = buffer.getvalue()
    if len(result) > asset_service.MAX_IMAGE_BYTES:
        raise HTTPException(502, "La imagen generada supera el tamaño máximo de la biblioteca")
    return result, "image/jpeg"


